#!/usr/bin/env python3
"""Generate lib/MpkMiniMk4Display/include/MpkOledFont.h, the anti-aliased glyph table the host uses to draw
the knob value on the MK4 screen with 0x71 pixel blits (the MK4's own text redraw flickers).

Needs Pillow. The default font is Arimo Bold (Apache License 2.0, metric-compatible with Arial):
    python3 tools/gen_oled_font.py --font /path/to/Arimo-Bold.ttf --size 20
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _deps import require  # noqa: E402

require("PIL")
from PIL import ImageFont  # noqa: E402

FIRST, LAST = 32, 126


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the MK4 OLED glyph table header (MpkOledFont.h).")
    ap.add_argument("--font", required=True, help="TTF file (Arimo-Bold.ttf)")
    ap.add_argument("--size", type=int, default=20, help="pixel size")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "lib", "MpkMiniMk4Display",
                                                  "include", "MpkOledFont.h"))
    args = ap.parse_args(argv)

    font = ImageFont.truetype(args.font, args.size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        mask = font.getmask(ch, mode="L")
        w, h = mask.size
        left, top, _, _ = font.getbbox(ch)
        data = bytes(mask)
        nibbles = [(data[i] * 15 + 127) // 255 for i in range(w * h)]
        if len(nibbles) % 2:
            nibbles.append(0)
        glyphs.append((len(bitmap), w, h, left, top, round(font.getlength(ch)), ch))
        bitmap += [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]

    name = os.path.splitext(os.path.basename(args.font))[0]
    out = [
        "#pragma once",
        "",
        f"// Generated by tools/gen_oled_font.py from {name} at {args.size} px. Do not edit by hand.",
        "// Arimo: Copyright 2010-2012 Google Corporation, Apache License 2.0.",
        "// 4-bit coverage, two pixels per byte (high nibble first), rows packed without padding.",
        "",
        "#include <cstdint>",
        "",
        "namespace MpkMiniMk4 {",
        "namespace OledFont {",
        "",
        "struct Glyph {",
        "    uint16_t offset;  // into BITMAP",
        "    uint8_t  width;",
        "    uint8_t  height;",
        "    int8_t   xOffset; // from the pen position",
        "    int8_t   yOffset; // from the top of the line box",
        "    uint8_t  advance;",
        "};",
        "",
        f"constexpr char    FIRST_CHAR  = {FIRST};",
        f"constexpr char    LAST_CHAR   = {LAST};",
        f"constexpr uint8_t LINE_HEIGHT = {ascent + descent};",
        "",
        f"constexpr Glyph GLYPHS[{len(glyphs)}] = {{",
    ]
    for off, w, h, left, top, adv, ch in glyphs:
        label = "space" if ch == " " else ("backslash" if ch == "\\" else ch)
        out.append(f"    {{{off:5d}, {w:2d}, {h:2d}, {left:2d}, {top:2d}, {adv:2d}}}, // {label}")
    out.append("};")
    out.append("")
    out.append(f"constexpr uint8_t BITMAP[{len(bitmap)}] = {{")
    for i in range(0, len(bitmap), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    out += ["};", "", "} // namespace OledFont", "} // namespace MpkMiniMk4", ""]

    with open(args.out, "w") as f:
        f.write("\n".join(out))
    print(f"{args.out}: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes, line height {ascent + descent}")


if __name__ == "__main__":
    main()
